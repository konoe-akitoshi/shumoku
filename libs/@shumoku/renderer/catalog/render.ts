/**
 * Writes the UI kit catalog: `catalog/kit.html` and the SVGs it links to (`catalog/svg/`),
 * drawn by the same `renderNetworkSvg` the CLI and the Server use. The files are plain HTML and
 * SVG, checked in, and open with no server. Run `bun run catalog` after changing the kit; it
 * reads `src/` as it is (svelte-loader.ts compiles the components), so nothing is built first.
 */

import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { darkTheme, lightTheme, readNetworkModel } from '@shumoku/core'
import { kitColors } from '../src/kit/colors'
import { resolveTokens } from '../src/kit/tokens'
import { renderNetworkSvg } from '../src/static'
import { fixtures, type Specimen, specimens } from './specimens'

const here = dirname(fileURLToPath(import.meta.url))
const svgDir = join(here, 'svg')
const fixtureDir = join(here, '../../core/src/input/fixtures/pass')

const themes = { light: lightTheme, dark: darkTheme } as const

const esc = (s: string) =>
  s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')

const fmt = (v: unknown) => (typeof v === 'number' ? String(Math.round(v * 100) / 100) : String(v))

function flatten(value: unknown, prefix = ''): [string, string][] {
  if (Array.isArray(value)) return [[prefix, value.map(fmt).join(', ')]]
  if (value !== null && typeof value === 'object') {
    return Object.entries(value).flatMap(([k, v]) => flatten(v, prefix ? `${prefix}.${k}` : k))
  }
  return [[prefix, fmt(value)]]
}

/** Draws a specimen in both themes; the HTML for its section. */
function section(s: Specimen): string {
  const shots = Object.entries(themes).map(([name, theme]) => {
    const file = `svg/${s.id}.${name}.svg`
    try {
      writeFileSync(join(here, file), renderNetworkSvg(readNetworkModel(s.yaml), { theme }))
      return `<a class="shot ${name}" href="${file}"><img src="${file}" alt="${esc(s.title)} (${name})" loading="lazy"></a>`
    } catch (e) {
      return `<pre class="error">${esc(e instanceof Error ? e.message : String(e))}</pre>`
    }
  })
  const files = s.files.map((f) => `<code>src/${f}</code>`).join(' ')
  return `<section id="${s.id}">
  <h2>${esc(s.title)}</h2>
  ${s.note ? `<p class="note">${esc(s.note)}</p>` : ''}
  ${files ? `<p class="files">${files}</p>` : ''}
  ${shots.join('\n  ')}
  <details><summary>YAML</summary><pre>${esc(s.yaml)}</pre></details>
</section>`
}

function tokenTables(): string {
  return Object.entries(resolveTokens())
    .map(([name, value]) => {
      const rows = flatten(value)
        .map(([k, v]) => `<tr><th>${esc(k || name)}</th><td>${esc(v)}</td></tr>`)
        .join('')
      return `<table><caption>${esc(name)}</caption><tbody>${rows}</tbody></table>`
    })
    .join('\n')
}

function colorTable(): string {
  const light = new Map(flatten(kitColors(lightTheme)))
  const dark = new Map(flatten(kitColors(darkTheme)))
  const chip = (v = '') =>
    /^(#|rgb|hsl)/.test(v) ? `<span class="chip" style="background:${esc(v)}"></span>` : ''
  const rows = [...light.keys()]
    .map((k) => {
      const l = light.get(k)
      const d = dark.get(k)
      return `<tr><th>${esc(k)}</th><td>${chip(l)}${esc(l ?? '')}</td><td>${chip(d)}${esc(d ?? '')}</td></tr>`
    })
    .join('')
  return `<table class="colors"><thead><tr><th></th><th>light</th><th>dark</th></tr></thead><tbody>${rows}</tbody></table>`
}

