// Inlines the sample YAML (data/) into a single TS module (src/generated-data.ts)
// so the tsc-built plugin carries its data without a runtime fs dependency.
//
// Usage:  node scripts/gen-data.mjs
// The output is committed; re-run after editing files under data/.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const dataDir = join(here, '..', 'data')
const outPath = join(here, '..', 'src', 'generated-data.ts')

function keyOf(file) {
  // topology-<id>.yaml -> <id> ; scenario-<id>.yml -> <id>
  return file.replace(/\.ya?ml$/, '')
}

const files = readdirSync(dataDir).sort()
const topologies = {}
const scenarios = {}
for (const f of files) {
  const text = readFileSync(join(dataDir, f), 'utf8')
  const key = keyOf(f)
  if (f.startsWith('topology-')) topologies[key.replace(/^topology-/, '')] = text
  else if (f.startsWith('scenario-')) scenarios[key.replace(/^scenario-/, '')] = text
}

const banner = [
  '// Copyright (C) 2026 system_explorer contributors',
  '// SPDX-License-Identifier: AGPL-3.0-only',
  '//',
  '// GENERATED by scripts/gen-data.mjs from ../data/*.yaml. Do not edit by hand.',
  '// Re-run the generator after changing a data file.',
  '',
].join('\n')

const body = [
  banner,
  '/** Sample id -> topology YAML (input.Network shape, see @shumoku/core readNetworkModel). */',
  'export const topologies: Record<string, string> = ' + JSON.stringify(topologies, null, 2) + ';',
  '',
  '/** Sample id -> scenario YAML (declarative scenario doc, see src/scenario/schema.ts). */',
  'export const scenarios: Record<string, string> = ' + JSON.stringify(scenarios, null, 2) + ';',
  '',
].join('\n')

writeFileSync(outPath, body)
console.log(
  `generated-data.ts: ${Object.keys(topologies).length} topologies, ${Object.keys(scenarios).length} scenarios`,
)
